def build_doc():
    from docx import Document
    from docx.shared import Pt, RGBColor, Inches
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    cINK = RGBColor(*INK); cSLATE = RGBColor(*SLATE); cSLATE_LT = RGBColor(*SLATE_LT)
    cACCENT = RGBColor(*ACCENT); cPLUM = RGBColor(*PLUM); cORANGE = RGBColor(*ORANGE)
    SH_GREEN = "EDF4ED"; SH_BLUE = "EAF1F7"; SH_PLUM = "F1EDF6"; SH_GREY = "F2F3F5"; HDR = "DCE6EF"

    doc = Document()
    nm = doc.styles["Normal"]; nm.font.name = "Calibri"; nm.font.size = Pt(11); nm.font.color.rgb = cINK
    nm.paragraph_format.space_after = Pt(8); nm.paragraph_format.line_spacing = 1.15
    for lvl, sz, col in [("Heading 1", 16, cSLATE), ("Heading 2", 13, cSLATE), ("Heading 3", 11.5, cSLATE_LT)]:
        st = doc.styles[lvl]; st.font.name = "Calibri"; st.font.size = Pt(sz); st.font.color.rgb = col; st.font.bold = True

    def shade(p, fill):
        pPr = p._p.get_or_add_pPr(); shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), fill); pPr.append(shd)

    def border(p, color="9DB6CC", size=18):
        pPr = p._p.get_or_add_pPr(); pbdr = OxmlElement("w:pBdr"); e = OxmlElement("w:left")
        e.set(qn("w:val"), "single"); e.set(qn("w:sz"), str(size)); e.set(qn("w:space"), "8"); e.set(qn("w:color"), color)
        pbdr.append(e); pPr.append(pbdr)

    def bullet(text, lead=None):
        p = doc.add_paragraph(style="List Bullet")
        if lead:
            r = p.add_run(lead); r.bold = True
        p.add_run(text); return p

    def field(label, text):
        p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(5)
        r = p.add_run(label + "  "); r.bold = True; r.font.color.rgb = cSLATE
        p.add_run(text); return p

    def box(text, fill=SH_GREY, bc="C9CDD3", lead=None, lc=cSLATE):
        p = doc.add_paragraph(); shade(p, fill); border(p, color=bc)
        if lead:
            r = p.add_run(lead); r.bold = True; r.font.color.rgb = lc
        r2 = p.add_run(text); r2.font.size = Pt(10.5)
        p.paragraph_format.space_after = Pt(10); return p

    fign = {"n": 0}
    def figure(img, caption, width=6.3):
        fign["n"] += 1
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(os.path.join(ASSETS, img), width=Inches(width))
        p.paragraph_format.space_before = Pt(6); p.paragraph_format.space_after = Pt(2)
        cap = doc.add_paragraph(); cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = cap.add_run(f"Figure {fign['n']}.  "); r.bold = True; r.font.size = Pt(9.5); r.font.color.rgb = cSLATE
        r2 = cap.add_run(caption); r2.font.size = Pt(9.5); r2.font.color.rgb = cINK
        cap.paragraph_format.space_after = Pt(12)

    def table(headers, rows, widths=None, fs=9.0):
        t = doc.add_table(rows=1, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.style = "Table Grid"
        for i, htext in enumerate(headers):
            c = t.rows[0].cells[i]; c.text = ""; p = c.paragraphs[0]
            r = p.add_run(htext); r.bold = True; r.font.size = Pt(fs + 0.5); r.font.color.rgb = cINK; shade(p, HDR)
            tcPr = c._tc.get_or_add_tcPr(); shd = OxmlElement("w:shd")
            shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), HDR); tcPr.append(shd)
        for ri, row in enumerate(rows):
            cells = t.add_row().cells
            for i, val in enumerate(row):
                cells[i].text = ""; p = cells[i].paragraphs[0]
                r = p.add_run(val); r.font.size = Pt(fs); r.font.color.rgb = cINK
                if ri % 2 == 1:
                    tcPr = cells[i]._tc.get_or_add_tcPr(); shd = OxmlElement("w:shd")
                    shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), "F6F8FA"); tcPr.append(shd)
        if widths:
            for row in t.rows:
                for i, w in enumerate(widths):
                    row.cells[i].width = Inches(w)
        doc.add_paragraph().paragraph_format.space_after = Pt(4); return t

    # -- Title --
    t = doc.add_paragraph(); t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = t.add_run("Weekly Meeting Update"); r.font.size = Pt(26); r.font.bold = True; r.font.color.rgb = cSLATE
    t.paragraph_format.space_before = Pt(10); t.paragraph_format.space_after = Pt(2)
    s = doc.add_paragraph(); s.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = s.add_run("What I found  \u00b7  what we can do as a remote intern  \u00b7  what needs discussion")
    r.font.size = Pt(13); r.font.color.rgb = cSLATE_LT
    s.paragraph_format.space_after = Pt(4)
    s2 = doc.add_paragraph(); s2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = s2.add_run("Direction: MetaAI paper (SIGCOMM 2025)  \u00b7  ESPectre Wi-Fi sensing repo  \u00b7  reduce-cameras idea")
    r.italic = True; r.font.size = Pt(10.5); r.font.color.rgb = cINK
    s2.paragraph_format.space_after = Pt(12)

    # -- TL;DR --
    h = doc.add_heading("In Short", level=1)
    box("MetaAI (computing AI inside the wireless channel) and our Wi-Fi sensing idea rest on the same physics, "
        "so MetaAI is a natural upgrade path for our idea, not a competitor.",
        fill=SH_GREEN, bc="AFC8B2", lead="What I found:  ", lc=cACCENT)
    box("I distilled six concrete projects that a remote intern can do for under fifteen dollars each \u2014 "
        "mostly a laptop and free data, with an eight-dollar ESP32 and a webcam for the hands-on ones.",
        fill=SH_BLUE, bc="9DB6CC", lead="What we can do:  ", lc=cSLATE)
    box("A few quick decisions from you would let me lock in the main project: scope, priority, a small budget, "
        "data access, and the target output.",
        fill=SH_PLUM, bc="B9A9D0", lead="What to discuss:  ", lc=cPLUM)
    figure("fig_three.png",
           "The whole meeting on one page: findings, feasible projects, and the decisions I need from you.", width=6.5)

    # -- PART 1 --
    doc.add_heading("1.  What I Found", level=1)
    field("The paper.", "MetaAI programs a metasurface so the wireless signal itself performs a neural-network "
          "layer: the device only transmits, the channel does the multiply-and-add, and the server receives the "
          "answer, not raw data. It reports 82.8 percent average accuracy with a single linear layer, plus up to "
          "27 percent from fusing sensors.")
    field("The connection.", "Wi-Fi sensing reads a person out of the wireless channel; MetaAI writes "
          "neural-network weights into that same channel. Same linear physics, read in one and programmed in the "
          "other \u2014 which is exactly why the paper and our reduce-cameras idea combine.")
    field("The honest split.", "MetaAI's software-side tricks (noise-aware and timing-robust training, principled "
          "fusion) can help our Wi-Fi models now. The metasurface hardware is a genuine frontier that must be "
          "validated on our through-wall data before we rely on it.")
    figure("fig_overview.png",
           "The two pieces meet at the shared wireless channel: our camera-taught Wi-Fi idea (left), MetaAI (right), "
           "combining into one richer system (centre).", width=6.4)
    box("Full detail is in the companion documents I prepared: the paper explainer, the combination study "
        "(MetaPerception), and the ideas catalogue. This update is the summary for today.",
        fill=SH_GREY, bc="C9CDD3")

    # -- PART 2 --
    doc.add_heading("2.  What We Can Do as a Remote Intern", level=1)
    para = doc.add_paragraph()
    para.add_run("Six concrete projects, all low-cost and doable remotely. Each has a clear method and a small "
                 "deliverable I can show week to week. Full write-ups (what/why/how, prior work, cost) are in the "
                 "ideas catalogue.")
    table(["#", "Project", "Cost", "Needs", "Novelty"], [
        ["1", "Over-the-air compute tested on through-wall CSI (simulation)", "~$0", "laptop, free data", "High"],
        ["2", "MetaAI training tricks to fix Wi-Fi's room-to-room failure", "~$0\u2013$8", "data (+opt ESP32)", "Medium"],
        ["3", "Poor-man's metasurface: foil reflectors to boost coverage", "<$15", "ESP32 + foil", "Med-High"],
        ["4", "Label-efficient CSI sensing via self-supervised learning", "~$0", "laptop, free data", "Medium"],
        ["5", "Camera-teaches-Wi-Fi on one ESP32 (reproducible pipeline)", "<$10", "ESP32 + webcam", "Med-High"],
        ["6", "How much can Wi-Fi identify you, and can we stop it cheaply", "<$10", "ESP32 / dataset", "Med-High"],
    ], widths=[0.35, 3.5, 0.85, 1.4, 0.9], fs=8.8)
    figure("fig_toolkit.png",
           "The complete kit: a laptop, free datasets, one or two eight-dollar ESP32 boards, a webcam, and some "
           "aluminium foil. Several ideas need no hardware at all.", width=6.3)
    field("My recommended start.", "Idea 2 first (no hardware, fast, a clear before/after number), order one ESP32 "
          "in parallel for Idea 5 (real data and a live demo), then build toward Idea 1 as the flagship result "
          "because it directly unites the two references you gave me.")

    # -- PART 3 --
    doc.add_heading("3.  What Needs to Be Discussed", level=1)
    para = doc.add_paragraph()
    para.add_run("A few decisions from you would let me commit to the main project and set a realistic plan:")
    bullet("simulation-first (Ideas 1, 2, 4, no hardware) or hands-on hardware (Ideas 3, 5, 6)?", lead="Scope: ")
    bullet("which idea should be the main project versus a quick side result?", lead="Priority: ")
    bullet("approval to buy one or two ESP32 CSI boards (about eight dollars each) and small parts?", lead="Budget: ")
    bullet("can I collect CSI at home or with volunteers, or should I stay with public datasets only?", lead="Data: ")
    bullet("are we aiming at a workshop paper, a demo, or an internal prototype?", lead="Target output: ")
    bullet("what would you like me to bring to each weekly meeting to show progress?", lead="Cadence: ")
    figure("fig_discuss.png", "The six decisions, at a glance.", width=6.3)

    # -- PART 4 --
    doc.add_heading("4.  What I Propose to Do This Week", level=1)
    bullet("set up a public CSI dataset and reproduce a baseline activity classifier (foundation for Ideas 1, 2, 4).", lead="Step 1: ")
    bullet("run MetaAI's training tricks as augmentation and measure the cross-room accuracy change (Idea 2).", lead="Step 2: ")
    bullet("if the budget is approved, order one ESP32 and begin the camera-teaches-Wi-Fi pipeline (Idea 5).", lead="Step 3: ")
    box("Everything above shares the same cheap toolkit, so nothing is locked in \u2014 your decisions today simply "
        "tell me which idea to push hardest.",
        fill=SH_GREEN, bc="AFC8B2", lead="In one line:  ", lc=cACCENT)

    closing = doc.add_paragraph(); closing.paragraph_format.space_before = Pt(8)
    r = closing.add_run("Companion documents available: the MetaAI paper explainer, the MetaPerception combination "
                        "study, and the low-cost ideas catalogue (with full method, prior work, and cost for each idea).")
    r.italic = True; r.font.size = Pt(9.5); r.font.color.rgb = cSLATE_LT

    doc.save(DOC_OUT); print("saved", DOC_OUT)


