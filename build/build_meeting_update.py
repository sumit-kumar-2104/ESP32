def build_ppt():
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
    from pptx.enum.shapes import MSO_SHAPE
    from PIL import Image

    cSLATE = RGBColor(*SLATE); cSLATE_LT = RGBColor(0x7C, 0x97, 0xB2); cACCENT = RGBColor(*ACCENT)
    cPLUM = RGBColor(*PLUM); cINK = RGBColor(0x3A, 0x3E, 0x44); cMUTE = RGBColor(0x8A, 0x8F, 0x96)
    cRULE = RGBColor(0xCF, 0xDA, 0xE4); cBG = RGBColor(0xFC, 0xFD, 0xFE)
    GREEN_FILL = RGBColor(0xED, 0xF4, 0xED); BLUE_FILL = RGBColor(0xEA, 0xF1, 0xF7); PLUM_FILL = RGBColor(0xF1, 0xED, 0xF6)
    ROW_FILL = RGBColor(0xF5, 0xF8, 0xFA)

    prs = Presentation(); prs.slide_width = Inches(13.333); prs.slide_height = Inches(7.5)
    SW, SH = prs.slide_width, prs.slide_height; BLANK = prs.slide_layouts[6]

    def slide():
        s = prs.slides.add_slide(BLANK)
        bg = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, SW, SH)
        bg.fill.solid(); bg.fill.fore_color.rgb = cBG; bg.line.fill.background(); bg.shadow.inherit = False
        s.shapes._spTree.remove(bg._element); s.shapes._spTree.insert(2, bg._element); return s

    def font(run, size, color, bold=False, italic=False):
        run.font.size = Pt(size); run.font.color.rgb = color; run.font.bold = bold
        run.font.italic = italic; run.font.name = "Calibri"

    def tbox(s, x, y, w, h, anchor=MSO_ANCHOR.TOP):
        tb = s.shapes.add_textbox(x, y, w, h); tf = tb.text_frame; tf.word_wrap = True
        tf.vertical_anchor = anchor
        tf.margin_left = 0; tf.margin_right = 0; tf.margin_top = 0; tf.margin_bottom = 0
        return tb, tf

    def rule(s, x, y, w):
        ln = s.shapes.add_connector(2, x, y, x + w, y); ln.line.color.rgb = cRULE; ln.line.width = Pt(1.5); return ln

    def tab(s, x, y, color=cSLATE):
        r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, Inches(0.07), Inches(0.42))
        r.fill.solid(); r.fill.fore_color.rgb = color; r.line.fill.background(); r.shadow.inherit = False

    def title(s, text, kicker=None):
        tab(s, Inches(0.6), Inches(0.55))
        tb, tf = tbox(s, Inches(0.85), Inches(0.42), Inches(11.9), Inches(0.8))
        p = tf.paragraphs[0]; r = p.add_run(); r.text = text; font(r, 28, cSLATE, bold=True)
        if kicker:
            p2 = tf.add_paragraph(); rk = p2.add_run(); rk.text = kicker; font(rk, 13, cSLATE_LT, italic=True)
        rule(s, Inches(0.62), Inches(1.42), Inches(12.1))

    def footer(s, idx):
        tb, tf = tbox(s, Inches(0.62), Inches(7.04), Inches(11.0), Inches(0.3))
        r = tf.paragraphs[0].add_run(); r.text = "Weekly meeting update  \u00b7  Wi-Fi sensing + over-the-air compute"
        font(r, 9, cMUTE)
        tb2, tf2 = tbox(s, Inches(12.2), Inches(7.04), Inches(0.7), Inches(0.3))
        p2 = tf2.paragraphs[0]; p2.alignment = PP_ALIGN.RIGHT; r2 = p2.add_run(); r2.text = str(idx); font(r2, 9, cMUTE)

    def bullets(s, items, x, y, w, h, size=17, gap=11):
        tb, tf = tbox(s, x, y, w, h); first = True
        for it in items:
            p = tf.paragraphs[0] if first else tf.add_paragraph(); first = False
            p.space_after = Pt(gap); p.line_spacing = 1.06
            m = p.add_run(); m.text = "\u2014  "; font(m, size, cACCENT)
            r = p.add_run(); r.text = it.get("t"); font(r, size, cINK, bold=it.get("b", False))
        return tb

    def chip(s, x, y, w, h, label, body, fill, ec):
        b = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, x, y, w, h)
        b.fill.solid(); b.fill.fore_color.rgb = fill; b.line.color.rgb = ec; b.line.width = Pt(1.0); b.shadow.inherit = False
        tf = b.text_frame; tf.word_wrap = True
        tf.margin_left = Inches(0.14); tf.margin_right = Inches(0.14); tf.margin_top = Inches(0.1); tf.margin_bottom = Inches(0.1)
        p = tf.paragraphs[0]; r = p.add_run(); r.text = label; font(r, 14, ec, bold=True)
        p2 = tf.add_paragraph(); r2 = p2.add_run(); r2.text = body; font(r2, 11.5, cINK)
        return b

    def picture(s, img, x, y, w):
        return s.shapes.add_picture(os.path.join(ASSETS, img), x, y, width=w)

    def picture_c(s, img, cx, y, w):
        return picture(s, img, cx - w // 2, y, w)

    # 1 Title
    s = slide()
    band = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(0.22), SH)
    band.fill.solid(); band.fill.fore_color.rgb = cSLATE; band.line.fill.background(); band.shadow.inherit = False
    tb, tf = tbox(s, Inches(0.9), Inches(2.15), Inches(11.9), Inches(2.2))
    r = tf.paragraphs[0].add_run(); r.text = "Weekly Meeting Update"; font(r, 44, cSLATE, bold=True)
    p2 = tf.add_paragraph(); r2 = p2.add_run()
    r2.text = "What I found  \u00b7  what we can do as a remote intern  \u00b7  what to discuss"; font(r2, 19, cSLATE_LT)
